#!/bin/bash
# Same-ISA passthrough differential test (docs/AOT.md, "Same-ISA passthrough").
#
#   tools/aot/tests/fp-passthrough/run.sh [--quick] [--out DIR] [--verbose]
#                                         [--cpu cortex-a76|max]
#
# Builds pttest.elf (bare-metal, NDK clang + ld.lld) and runs it on -M virt
# -cpu cortex-a76 (the app's CPU; --cpu max adds FEAT_AFP, so the FPCR.AH /
# FIZ / NEP settings of pttest.c take effect) under
#   1. JIT       engine/build-macos-aot-jit
#   2. TCTI      engine/build-macos-aot-tcti
#   3. TCTI + AOT cache from a TCTI capture of the same program (every TB is
#      captured: no QEMU_AOT_HOT), generated by tcg2c.py
#        a. passthrough, with per-helper inline/fallback counters (--pt-stats)
#        b. passthrough, production build (native chaining, no stats)
#        c. --pt-fpsr variant
#        d. --no-passthrough (the old code)
#        e. verify variant: QEMU_AOT_VERIFY=1 (every execution compared
#           against TCTI; --quick: every 16th)
# and checks that all outputs are identical, that every TB of the program is
# a table hit and that the verifier reports 0 mismatches.  Exit status 0 on
# success.  --verbose prints every test case (large output).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../../.." && pwd)"
OUT="$ROOT/engine/run/pt-fptest"
VERIFY=1
EXTRA=
CPU=cortex-a76
while [ $# -gt 0 ]; do
    case "$1" in
    --quick ) VERIFY=16 ;;
    --out ) OUT="$2"; shift ;;
    --verbose ) EXTRA=-DPT_VERBOSE ;;
    --cpu ) CPU="$2"; shift ;;
    -h | --help ) sed -n 2,25p "$0"; exit 0 ;;
    * ) echo "unknown option $1" >&2; exit 2 ;;
    esac
    shift
done
JIT="$ROOT/engine/build-macos-aot-jit/qemu-system-aarch64"
TCTI="$ROOT/engine/build-macos-aot-tcti/qemu-system-aarch64"
for q in "$JIT" "$TCTI"; do
    [ -x "$q" ] || { echo "missing $q (tools/aot/build-variants.sh)" >&2; exit 1; }
done
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
make -s -C "$HERE" OUT="$OUT" EXTRA="$EXTRA" "$OUT/pttest.elf"
ELF="$OUT/pttest.elf"

run() {     # run NAME QEMU [ENV...]: serial output in $OUT/NAME.txt
    local name="$1" q="$2"
    shift 2
    local t0=$(date +%s)
    env "$@" "$q" -M virt -cpu "$CPU" -smp 1 -m 256 -display none -monitor none \
        -serial "file:$OUT/$name.txt" -kernel "$ELF" > "$OUT/$name.stderr" 2>&1
    echo "  $name: $(( $(date +%s) - t0 )) s, $(tail -2 "$OUT/$name.txt" | head -1)"
}

gen() {     # gen DIR [tcg2c flags]
    local d="$1"
    shift
    rm -rf "$d"
    python3 -I "$ROOT/tools/aot/tcg2c.py" "$OUT/ops-capture.txt" --out "$d" --qemu "$TCTI" "$@" \
        | sed 's/^/    /'
    ninja -C "$d" -j "${NCPU:-6}" libaot.dylib libaot-verify.dylib > "$d/build.log" 2>&1 ||
        { tail -20 "$d/build.log"; exit 1; }
}

echo "pt-test: $ELF, -cpu $CPU"
run jit "$JIT"
run tcti "$TCTI"
run capture "$TCTI" QEMU_AOT_CAPTURE="$OUT/ops-capture.txt"
echo "  captured $(grep -c "^TB " "$OUT/ops-capture.txt") TBs"
gen "$OUT/gen-pt" --pt-stats
gen "$OUT/gen-prod"
gen "$OUT/gen-fpsr" --pt-fpsr --pt-stats
gen "$OUT/gen-nopt" --no-passthrough
run aot-pt "$TCTI" QEMU_AOT_LIB="$OUT/gen-pt/libaot.dylib" QEMU_AOT_STATS="$OUT/aot-pt.json" AOT_PT_STATS=1
run aot-prod "$TCTI" QEMU_AOT_LIB="$OUT/gen-prod/libaot.dylib"
run aot-fpsr "$TCTI" QEMU_AOT_LIB="$OUT/gen-fpsr/libaot.dylib" QEMU_AOT_STATS="$OUT/aot-fpsr.json" AOT_PT_STATS=1
run aot-nopt "$TCTI" QEMU_AOT_LIB="$OUT/gen-nopt/libaot.dylib" QEMU_AOT_STATS="$OUT/aot-nopt.json"
run verify "$TCTI" QEMU_AOT_LIB="$OUT/gen-pt/libaot-verify.dylib" QEMU_AOT_VERIFY=$VERIFY \
    QEMU_AOT_STATS="$OUT/verify.json"

python3 -I - "$OUT" <<'PYEOF'
import json, sys, os
out = sys.argv[1]
ok = True
ref = open(os.path.join(out, "jit.txt")).read()
for n in ("tcti", "capture", "aot-pt", "aot-prod", "aot-fpsr", "aot-nopt", "verify"):
    t = open(os.path.join(out, n + ".txt")).read()
    same = t == ref
    ok &= same
    print(f"  output {n:9s} {'identical to JIT' if same else 'DIFFERS from JIT'}")
if "DONE" not in ref or "KAT failures: 0" not in ref:
    print("  JIT run incomplete or known-answer failures")
    ok = False
ntb = sum(1 for l in open(os.path.join(out, "ops-capture.txt")) if l.startswith("TB "))
for n in ("aot-pt", "aot-fpsr", "aot-nopt", "verify"):
    s = json.load(open(os.path.join(out, n + ".json")))
    hits = s["lookup_hit"] == ntb and s["aot_tbs"] == ntb and s["fp_mismatch"] == 0
    ok &= hits
    line = f"  {n:9s} table hits {s['lookup_hit']}/{ntb}, AOT TBs {s['aot_tbs']}, AOT execs {s['aot_execs']}"
    if n == "verify":
        line += (f", compared {s['v_compared']}, not replayable {s['v_unsafe']},"
                 f" mismatches {s['v_mismatch']} (flaky {s['v_flaky']})")
        ok &= s["v_mismatch"] == 0 and s["v_compared"] > 0
    print(line)
for n in ("aot-pt", "aot-fpsr"):
    inl = fb = 0
    kinds = 0
    for l in open(os.path.join(out, n + ".stderr")):
        if l.startswith("aot-pt "):
            p = l.split()
            inl += int(p[3]); fb += int(p[5]); kinds += 1
    print(f"  {n:9s} passthrough: {kinds} helpers, {inl} inline, {fb} fallback calls")
    ok &= kinds > 0 and inl > 0
print("PASS" if ok else "FAIL")
sys.exit(0 if ok else 1)
PYEOF
