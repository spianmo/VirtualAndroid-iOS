# Shared environment for the iOS / iOS Simulator cross builds.
# Sourced by build_deps.sh and build_qemu.sh; expects PLATFORM and ARCH set.
#
#   PLATFORM  ios | ios_simulator
#   ARCH      arm64
#   NCPU      parallel jobs (default 6)
#   DEBUG     non-empty: -g -O0 / debug buildtype
#
# Layout (all under engine/build-ios, git-ignored):
#   <platform>-<arch>/src/<pkg>        unpacked + patched sources (built in tree)
#   <platform>-<arch>/sysroot          install prefix (include, lib, lib/pkgconfig)
#   <platform>-<arch>/Frameworks       dependency dylibs wrapped as .framework
#   <platform>-<arch>/stamps           idempotence markers
#   <platform>-<arch>/qemu-<backend>/  QEMU build, install and framework

set -e

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
DL="$ROOT/third_party/dl"
UTM="$ROOT/third_party/UTM"
UTM_PATCHES="$UTM/patches"
OUT="${OUT:-$ROOT/engine/build-ios}"
LOGDIR="$ROOT/.logs"

IOS_SDKMINVER="${IOS_SDKMINVER:-15.0}"
ARCH="${ARCH:-arm64}"
NCPU="${NCPU:-6}"

GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m'
say () { printf "${GREEN}[ios-build %s] %s${NC}\n" "$PLATFORM" "$*"; }
die () { printf "${RED}[ios-build %s] %s${NC}\n" "$PLATFORM" "$*" >&2; exit 1; }

case "$PLATFORM" in
ios_simulator )
    SDK=iphonesimulator
    CFLAGS_TARGET="-target $ARCH-apple-ios$IOS_SDKMINVER-simulator"
    MESON_SUBSYSTEM=ios-simulator
    XCF_PLATFORM=ios-simulator
    ;;
ios )
    SDK=iphoneos
    CFLAGS_TARGET="-target $ARCH-apple-ios$IOS_SDKMINVER"
    MESON_SUBSYSTEM=ios
    XCF_PLATFORM=ios
    ;;
* )
    die "PLATFORM must be ios or ios_simulator (got '$PLATFORM')"
    ;;
esac
case "$ARCH" in
arm64 ) CPU=aarch64 ;;
* ) die "only arm64 is supported" ;;
esac
CHOST=$CPU-apple-darwin

PLAT_DIR="$OUT/$PLATFORM-$ARCH"
PREFIX="$PLAT_DIR/sysroot"
SRCROOT="$PLAT_DIR/src"
FRAMEWORKS="$PLAT_DIR/Frameworks"
STAMPS="$PLAT_DIR/stamps"
mkdir -p "$PREFIX/lib/pkgconfig" "$PREFIX/include" "$PREFIX/host/bin" "$SRCROOT" "$FRAMEWORKS" "$STAMPS" "$LOGDIR"

SDKROOT="$(xcrun --sdk $SDK --show-sdk-path)"
SDKVERSION="$(xcrun --sdk $SDK --show-sdk-version)"

# Host tools: Homebrew bison first, our pkg-config wrapper next. Never let
# /usr/local (x86 Homebrew leftovers) or the host pkg-config path leak in.
export PATH="$PREFIX/host/bin:/opt/homebrew/opt/bison/bin:$(echo "$PATH" | tr ':' '\n' | grep -v '^/usr/local' | paste -sd: -)"
unset PKG_CONFIG_PATH PKG_CONFIG_SYSROOT_DIR
export PKG_CONFIG="$PREFIX/host/bin/pkg-config"
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"

CC="$(xcrun --sdk $SDK --find clang) $CFLAGS_TARGET"
CPP="$(xcrun --sdk $SDK --find clang) $CFLAGS_TARGET -E"
CXX="$(xcrun --sdk $SDK --find clang++) $CFLAGS_TARGET"
OBJCC="$(xcrun --sdk $SDK --find clang) $CFLAGS_TARGET"
LD="$(xcrun --sdk $SDK --find ld)"
AR="$(xcrun --sdk $SDK --find ar)"
NM="$(xcrun --sdk $SDK --find nm)"
RANLIB="$(xcrun --sdk $SDK --find ranlib)"
STRIP="$(xcrun --sdk $SDK --find strip)"
export CC CPP CXX OBJCC LD AR NM RANLIB STRIP

if [ -n "$DEBUG" ]; then
    DEBUG_FLAGS="-g -O0"; MESON_BUILDTYPE=debug
else
    DEBUG_FLAGS=""; MESON_BUILDTYPE=release
fi
COMMON_FLAGS="-arch $ARCH -isysroot $SDKROOT $CFLAGS_TARGET -I$PREFIX/include $DEBUG_FLAGS"
export CFLAGS="$COMMON_FLAGS"
export CPPFLAGS="$COMMON_FLAGS"
export CXXFLAGS="$COMMON_FLAGS"
export OBJCFLAGS="$COMMON_FLAGS"
export LDFLAGS="-arch $ARCH -isysroot $SDKROOT $CFLAGS_TARGET -L$PREFIX/lib $DEBUG_FLAGS"

# AC_CHECK_FUNCS declares its own prototype and so misses SDK availability
# attributes (same workaround as UTM).
export ac_cv_func_pipe2=no
export ac_cv_func_dup3=no

# pkg-config wrapper: host pkg-config restricted to the sysroot.
write_pkg_config_wrapper () {
    host_pkgconfig="$(command -v /opt/homebrew/bin/pkg-config || command -v pkg-config)"
    cat > "$PREFIX/host/bin/pkg-config" <<EOF
#!/bin/sh
# generated by engine/scripts/ios/common.sh: only the $PLATFORM sysroot is visible
PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"
export PKG_CONFIG_LIBDIR
unset PKG_CONFIG_PATH
exec "$host_pkgconfig" "\$@"
EOF
    chmod +x "$PREFIX/host/bin/pkg-config"
}

meson_quote () {
    printf "'%s'" "$(echo $* | sed "s/ /','/g")"
}

# $1 = output file, $2 = meson host system ('ios' for most deps, 'darwin' for
# libslirp, as in UTM's build_dependencies.sh)
generate_meson_cross () {
    cross="$1"; system="$2"
    {
    echo "# Automatically generated by engine/scripts/ios/common.sh - do not modify"
    echo "[properties]"
    echo "needs_exe_wrapper = true"
    echo "has_function_pipe2 = false"
    echo "has_function_dup3 = false"
    echo "pkg_config_libdir = ['$PREFIX/lib/pkgconfig', '$PREFIX/share/pkgconfig']"
    echo "[built-in options]"
    echo "c_args = [$(meson_quote $CFLAGS)]"
    echo "cpp_args = [$(meson_quote $CXXFLAGS)]"
    echo "objc_args = [$(meson_quote $OBJCFLAGS)]"
    echo "c_link_args = [$(meson_quote $LDFLAGS)]"
    echo "cpp_link_args = [$(meson_quote $LDFLAGS)]"
    echo "objc_link_args = [$(meson_quote $LDFLAGS)]"
    echo "[binaries]"
    echo "c = [$(meson_quote $CC)]"
    echo "cpp = [$(meson_quote $CXX)]"
    echo "objc = [$(meson_quote $OBJCC)]"
    echo "ar = ['$AR']"
    echo "nm = ['$NM']"
    echo "ranlib = ['$RANLIB']"
    echo "strip = ['$STRIP', '-x']"
    echo "pkg-config = ['$PREFIX/host/bin/pkg-config']"
    echo "pkgconfig = ['$PREFIX/host/bin/pkg-config']"
    echo "python = ['$(command -v python3)']"
    echo "[host_machine]"
    echo "system = '$system'"
    if [ "$system" = darwin ]; then
        echo "kernel = 'xnu'"
        echo "subsystem = '$MESON_SUBSYSTEM'"
    fi
    echo "cpu_family = '$CPU'"
    echo "cpu = '$ARCH'"
    echo "endian = 'little'"
    } > "$cross"
}

# ---- framework packaging (after UTM scripts/fixup.sh, Apache-2.0) ----------

# framework name of a dylib: libglib-2.0.0.dylib -> glib-2.0.0
framework_name () {
    b="$(basename "$1")"; b="${b%.*}"; echo "${b#lib}"
}

# Rewrite imports that point into the sysroot (absolute or @rpath) to
# @rpath/<name>.framework/<name>. $1 = binary, rest = framework search dirs.
fixup_imports () {
    _file="$1"; shift
    otool -L "$_file" | tail -n +2 | awk '{print $1}' | while read -r g; do
        case "$g" in /usr/lib/* | /System/* ) continue ;; esac
        base="$(basename "$g")"
        name="$(framework_name "$g")"
        found=
        for d in "$@"; do [ -d "$d/$name.framework" ] && found=y; done
        [ -f "$PREFIX/lib/$base" ] && found=y
        if [ -n "$found" ]; then
            new="@rpath/$name.framework/$name"
            [ "$g" = "$new" ] || install_name_tool -change "$g" "$new" "$_file" 2>/dev/null
        fi
    done
}

# $1 = dylib, $2 = destination Frameworks dir, rest = extra framework dirs
make_framework () {
    file="$1"; dest="$2"; shift 2
    name="$(framework_name "$file")"
    fw="$dest/$name.framework"
    rm -rf "$fw"; mkdir -p "$fw"
    cp "$file" "$fw/$name"
    chmod u+w "$fw/$name"
    minos="$(vtool -show-build-version "$file" 2>/dev/null | awk '/minos/ {print $2; exit}')"
    [ -n "$minos" ] || minos="$IOS_SDKMINVER"
    if [ "$PLATFORM" = ios_simulator ]; then plat=iPhoneSimulator; else plat=iPhoneOS; fi
    bid="dev.virtualandroid.$(echo "$name" | tr '_.' '--')"
    cat > "$fw/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>CFBundleExecutable</key><string>$name</string>
	<key>CFBundleIdentifier</key><string>$bid</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleName</key><string>$name</string>
	<key>CFBundlePackageType</key><string>FMWK</string>
	<key>CFBundleShortVersionString</key><string>1.0</string>
	<key>CFBundleVersion</key><string>1</string>
	<key>CFBundleSupportedPlatforms</key><array><string>$plat</string></array>
	<key>MinimumOSVersion</key><string>$minos</string>
</dict>
</plist>
PLIST
    install_name_tool -id "@rpath/$name.framework/$name" "$fw/$name" 2>/dev/null
    fixup_imports "$fw/$name" "$dest" "$@"
    # install_name_tool invalidates the signature; re-sign ad hoc (the app
    # build re-signs embedded frameworks with the real identity).
    codesign --force --sign - --timestamp=none "$fw/$name" >/dev/null 2>&1
}

stamp_done () { [ -f "$STAMPS/$1.done" ]; }
stamp_set () { touch "$STAMPS/$1.done"; }
